/**
 * Pre-generates one MP3 per scenario node into public/audio and writes
 * src/content/audio-manifest.ts. Free: uses Microsoft Edge's neural voices (no API key).
 * Run after editing any scenario text:  npm run audio
 * Files are named with a hash of the spoken text, so unchanged lines are never regenerated.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { MsEdgeTTS, OUTPUT_FORMAT } from 'msedge-tts';
import { ALL_SCENARIOS } from '../src/content/scenarios';
import { prepareSpeechText } from '../src/lib/speech-text';

const VOICES: Record<string, string> = {
  bn: 'bn-BD-PradeepNeural',
  en: 'en-US-GuyNeural',
};

const OUT_DIR = join(process.cwd(), 'public', 'audio');
const MANIFEST = join(process.cwd(), 'src', 'content', 'audio-manifest.ts');

async function synth(voice: string, text: string): Promise<Buffer> {
  const tts = new MsEdgeTTS();
  await tts.setMetadata(voice, OUTPUT_FORMAT.AUDIO_24KHZ_48KBITRATE_MONO_MP3);
  const { audioStream } = await tts.toStream(text);
  const chunks: Buffer[] = [];
  await new Promise<void>((resolve, reject) => {
    audioStream.on('data', (c: Buffer) => chunks.push(c));
    audioStream.on('end', () => resolve());
    audioStream.on('error', reject);
  });
  tts.close();
  return Buffer.concat(chunks);
}

async function main() {
  const manifest: Record<string, string> = {};
  const keep = new Set<string>();

  for (const scenario of ALL_SCENARIOS) {
    const lang = scenario.locale.split('-')[0];
    const voice = VOICES[lang] ?? VOICES.en;
    const dir = join(OUT_DIR, scenario.id);
    mkdirSync(dir, { recursive: true });

    for (const [nodeId, node] of Object.entries(scenario.nodes)) {
      // Must match the text ScenarioPlayer speaks for a node
      const text = prepareSpeechText(node.messages.map((m) => m.spokenText || m.text).join('. '));
      if (!text) continue;

      const hash = createHash('sha1').update(`${voice}|${text}`).digest('hex').slice(0, 8);
      const file = `${nodeId}.${hash}.mp3`;
      const path = join(dir, file);
      keep.add(path);

      if (!existsSync(path)) {
        let audio: Buffer | null = null;
        for (let attempt = 1; attempt <= 3 && !audio; attempt++) {
          try {
            audio = await synth(voice, text);
          } catch (err) {
            console.warn(`  retry ${attempt} for ${scenario.id}/${nodeId}:`, (err as Error).message);
          }
        }
        if (!audio || audio.length === 0) throw new Error(`Failed to generate ${scenario.id}/${nodeId}`);
        writeFileSync(path, audio);
        console.log(`generated ${scenario.id}/${file} (${Math.round(audio.length / 1024)} KB)`);
      }
      manifest[`${scenario.id}/${nodeId}`] = `/audio/${scenario.id}/${file}`;
    }

    // Remove stale files from earlier text versions
    for (const f of readdirSync(dir)) {
      if (!keep.has(join(dir, f))) rmSync(join(dir, f));
    }
  }

  writeFileSync(
    MANIFEST,
    `// Generated by scripts/generate-audio.ts — do not edit by hand.\nexport const AUDIO_MANIFEST: Record<string, string> = ${JSON.stringify(manifest, null, 2)};\n\nexport function getStaticAudioUrl(scenarioId: string, nodeId: string): string | undefined {\n  return AUDIO_MANIFEST[\`\${scenarioId}/\${nodeId}\`];\n}\n`
  );
  console.log(`Done: ${Object.keys(manifest).length} clips.`);
}

main().then(() => process.exit(0), (err) => {
  console.error(err);
  process.exit(1);
});
